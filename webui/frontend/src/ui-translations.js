function translateText(value) {
  const leading = value.match(/^\s*/)?.[0] || ''
  const trailing = value.match(/\s*$/)?.[0] || ''
  const key = value.slice(leading.length, value.length - trailing.length)
  if (!key) return value
  if (Object.prototype.hasOwnProperty.call(AR, key)) return `${leading}${AR[key]}${trailing}`
  for (const [pattern, replace] of dynamicPatterns) {
    const match = pattern.exec(key)
    if (match) return `${leading}${replace(match)}${trailing}`
  }
  return value
}

export function translateUiText(value, locale = 'ar') {
  const text = String(value ?? '')
  return locale === 'ar' ? translateText(text) : text
}

const textState = new WeakMap()
const attrState = new WeakMap()
let observer
let activeLocale = 'zh-CN'
const translatedAttributes = ['placeholder', 'title', 'aria-label', 'alt']

function shouldSkipText(node) {
  const parent = node.parentElement
  return !parent || !!parent.closest('script, style, textarea, input, pre, code, [contenteditable="true"], .mono, .log-box')
}

function localizeTextNode(node) {
  if (shouldSkipText(node)) return
  const previous = textState.get(node)
  const source = previous && node.nodeValue === previous.applied ? previous.source : node.nodeValue
  const applied = translateUiText(source, activeLocale)
  textState.set(node, { source, applied })
  if (node.nodeValue !== applied) node.nodeValue = applied
}

function localizeAttributes(element) {
  let state = attrState.get(element)
  if (!state) { state = new Map(); attrState.set(element, state) }
  for (const name of translatedAttributes) {
    if (!element.hasAttribute(name)) continue
    const current = element.getAttribute(name) || ''
    const previous = state.get(name)
    const source = previous && current === previous.applied ? previous.source : current
    const applied = translateUiText(source, activeLocale)
    state.set(name, { source, applied })
    if (current !== applied) element.setAttribute(name, applied)
  }
}

function localizeSubtree(root) {
  if (!root) return
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node
  while ((node = walker.nextNode())) localizeTextNode(node)
  if (root.nodeType === Node.ELEMENT_NODE) localizeAttributes(root)
  root.querySelectorAll?.('*').forEach(localizeAttributes)
}

export function applyUiLocale(locale) {
  activeLocale = locale === 'ar' ? 'ar' : 'zh-CN'
  if (typeof document === 'undefined') return
  document.documentElement.lang = activeLocale === 'ar' ? 'ar' : 'zh-CN'
  document.documentElement.dir = activeLocale === 'ar' ? 'rtl' : 'ltr'
  document.body?.classList.toggle('locale-ar', activeLocale === 'ar')
  localizeSubtree(document.body)
}

export function observeUiLocale() {
  if (typeof document === 'undefined' || !document.body) return
  if (!observer) {
    observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === 'characterData') localizeTextNode(record.target)
        else if (record.type === 'attributes') localizeAttributes(record.target)
        else for (const node of record.addedNodes) {
          if (node.nodeType === Node.TEXT_NODE) localizeTextNode(node)
          else if (node.nodeType === Node.ELEMENT_NODE) localizeSubtree(node)
        }
      }
    })
    observer.observe(document.body, {
      subtree: true, childList: true, characterData: true, attributes: true,
      attributeFilter: translatedAttributes,
    })
  }
  applyUiLocale(activeLocale)
}
